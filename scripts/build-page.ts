// Bundles the page (web/index.html and what it imports) for production and writes it into
// src/page.gen.js as an importable module, with og.png alongside. Hosts deploy whatever the
// server imports, so nothing depends on a host shipping or serving loose files (Vercel's Bun
// runtime doesn't support HTML imports in routes). Run by `bun run build` (Vercel's build step),
// and by the server itself at startup in production elsewhere.
const WEB = `${import.meta.dir}/../web`;
const OUT = `${import.meta.dir}/../src/page.gen.js`;

const build = await Bun.build({ entrypoints: [`${WEB}/index.html`], minify: true });
if (!build.success) {
  for (const log of build.logs) console.error(log);
  process.exit(1);
}

type Asset = { type: string; base64: string };
let html = "";
const assets: Record<string, Asset> = {};
for (const output of build.outputs) {
  const path = output.path.replace(/^\.?\//, "/");
  if (path === "/index.html") {
    html = await output.text();
    continue;
  }
  assets[path] = { type: output.type, base64: Buffer.from(await output.arrayBuffer()).toString("base64") };
}
if (!html) throw new Error("the build produced no index.html");
const og = Bun.file(`${WEB}/og.png`);
assets["/og.png"] = { type: "image/png", base64: Buffer.from(await og.arrayBuffer()).toString("base64") };

await Bun.write(
  OUT,
  `// Generated by scripts/build-page.ts: do not edit. Types in page.gen.d.ts.\n` +
    `export const html = ${JSON.stringify(html)};\n` +
    `export const assets = ${JSON.stringify(assets)};\n`,
);
console.log(`page: ${Object.keys(assets).length} assets -> src/page.gen.js`);
