// Bundles src/app.ts with every package it imports into src/app.gen.js, which src/server.ts runs
// on Vercel. Vercel's Bun runtime didn't ship node_modules with the function, so nothing in the
// bundle may be left to resolve at runtime except Bun's own modules. Run by `bun run build`, after
// scripts/build-page.ts: the page it writes to src/page.gen.js is bundled in too.
const SRC = `${import.meta.dir}/../src`;

const build = await Bun.build({
  entrypoints: [`${SRC}/app.ts`],
  target: "bun",
  format: "esm",
  minify: true,
});
if (!build.success) {
  for (const log of build.logs) console.error(log);
  process.exit(1);
}
if (build.outputs.length !== 1) throw new Error(`expected one output, got ${build.outputs.length}`);

const code = await build.outputs[0]!.text();
await Bun.write(`${SRC}/app.gen.js`, `// Generated by scripts/build-server.ts: do not edit. Types in app.gen.d.ts.\n${code}`);
console.log(`server: src/app.ts -> src/app.gen.js (${Math.round(code.length / 1024)} KB)`);
